#!/usr/bin/env python3
"""Regenerate recipes/curated_index.json: Hub id -> scripts/reproduce_llm.sh key, for every key in
that script's KEYS whose case line names a Hub repo. scripts/convert.py prints the pointer when it
is asked to convert one of these repos (and runs the recipe with --curated).

    python3 scripts/gen_curated_index.py          # rewrite the index
    python3 scripts/gen_curated_index.py --check  # exit 1 if the index is out of date

A Hub id is an `org/name` token whose org is not a directory of this repo and whose name has no
file extension (so `templates/x.jinja`, `out/$key` and `qwen3_work/x.sh` are not ids).
"""
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCRIPT = ROOT / "scripts" / "reproduce_llm.sh"
INDEX = ROOT / "recipes" / "curated_index.json"
TOKEN = re.compile(r"(?<![\w/$.-])([A-Za-z0-9][\w.-]*)/([A-Za-z0-9][\w.-]*)(?![\w/$])")
EXT = re.compile(r"\.(jinja|py|sh|json|litertlm|md|txt|toml)$")


def build():
    text = SCRIPT.read_text()
    keys = re.search(r'^KEYS="(.*?)"', text, flags=re.MULTILINE | re.DOTALL).group(1)
    keys = keys.replace("\\\n", " ").split()
    body = text[text.index('case "$key" in'):text.index("  esac")]
    arms = list(re.finditer(r"^  ([a-z0-9][a-z0-9._-]*)\)", body, flags=re.MULTILINE))
    ids_by_key = {}
    for n, m in enumerate(arms):
        end = arms[n + 1].start() if n + 1 < len(arms) else len(body)
        code = "\n".join(line.split("#", 1)[0] for line in body[m.end():end].splitlines())
        ids = []
        for org, name in TOKEN.findall(code):
            if (ROOT / org).exists() or EXT.search(name) or f"{org}/{name}" in ids:
                continue
            ids.append(f"{org}/{name}")
        ids_by_key[m.group(1)] = ids
    models, without = {}, []
    for key in keys:
        if not ids_by_key.get(key):
            without.append(key)
        for hub_id in ids_by_key.get(key, []):
            models.setdefault(hub_id, key)
    return {
        "doc": "Hub id -> scripts/reproduce_llm.sh key of the models this repo ships with a "
               "hand-made recipe. Generated by scripts/gen_curated_index.py; do not edit by hand.",
        "source": "scripts/reproduce_llm.sh",
        "source_sha256": hashlib.sha256(SCRIPT.read_bytes()).hexdigest(),
        "models": dict(sorted(models.items())),
        "keys_without_hub_id": without,
    }


def main():
    index = build()
    text = json.dumps(index, indent=2) + "\n"
    if "--check" in sys.argv[1:]:
        current = INDEX.read_text() if INDEX.exists() else ""
        print("up to date" if current == text else "out of date: run scripts/gen_curated_index.py")
        return 0 if current == text else 1
    INDEX.write_text(text)
    print(f"{INDEX.relative_to(ROOT)}: {len(index['models'])} Hub ids, "
          f"{len(index['keys_without_hub_id'])} keys without one")
    return 0


if __name__ == "__main__":
    sys.exit(main())
