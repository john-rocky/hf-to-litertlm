#!/usr/bin/env python3
"""LlmExecutorMetadata from a prefill / decode .tflite's signatures, and its insertion into a builder TOML.

  executor_skeleton.py gen --tflite PREFILL_DECODE.tflite --out executor_metadata.pbtext [--compare SHIPPED.pbtext]
  executor_skeleton.py insert --toml IN.toml --pbtext executor_metadata.pbtext --out OUT.toml

gen reads the signature defs and tensor shapes from the flatbuffer (no interpreter) and writes an ExecutorMetadata
pbtext (the public builder's `executor_metadata --path` input) with one state_buffers entry per KV cache:
  * state tensors = names that are both inputs and outputs of the decode signature;
  * each must be named kv_cache_k_<n> (TYPE_GLOBAL_KEY_CACHE) or kv_cache_v_<n> (TYPE_GLOBAL_VALUE_CACHE) and be an
    input and an output of every prefill signature; anything else (a linear-attention / SSM state, a renamed cache)
    is not guessed: gen writes nothing and exits 3;
  * sequence_axis = the one axis whose size equals the decode signature's `mask` last dimension (else K -> 2,
    V -> 3, noted); maximum_sequence_length = that size.
max_history_size and attention_mask_settings are not written (they are not readable from the signatures).
The text is parsed back with executor_metadata_pb2; --compare prints the differences to a shipped section's pbtext.
insert adds `[[section]] section_type = "ExecutorMetadata"` right after the LlmMetadata section (first when there is
none); it refuses a TOML that already has one. Exit 0 = written, 2 = bad input, 3 = refused.
"""
import argparse
import json
import os
import re
import sys
import tomllib

from ai_edge_litert import schema_py_generated as S

KV = re.compile(r"^kv_cache_([kv])_(\d+)$")
MARK = "[[section]]"


def signatures(path):
    buf = open(path, "rb").read()
    m = S.Model.GetRootAs(buf, 0)
    out = {}
    for k in range(m.SignatureDefsLength()):
        sd = m.SignatureDefs(k)
        sg = m.Subgraphs(sd.SubgraphIndex())

        def side(n, get):
            d = {}
            for j in range(n):
                tm = get(j)
                t = sg.Tensors(tm.TensorIndex())
                d[tm.Name().decode()] = [int(t.Shape(x)) for x in range(t.ShapeLength())]
            return d
        out[sd.SignatureKey().decode()] = dict(inputs=side(sd.InputsLength(), sd.Inputs),
                                               outputs=side(sd.OutputsLength(), sd.Outputs))
    return out


def gen(a):
    sigs = signatures(a.tflite)
    pre = sorted(k for k in sigs if k.startswith("prefill"))
    dec = sorted(k for k in sigs if k.startswith("decode"))
    if not pre or not dec:
        print(f"REFUSED: no prefill* / decode* signatures in {sorted(sigs)}")
        return 3
    dk = dec[0]
    states = sorted(set(sigs[dk]["inputs"]) & set(sigs[dk]["outputs"]))
    unknown = [n for n in states if not KV.match(n)]
    if unknown or not states:
        print(f"REFUSED: decode state tensors that are not kv_cache_k_<n> / kv_cache_v_<n>: {unknown or 'none found'}")
        return 3
    notes = []
    for k in pre + dec[1:]:
        miss = [n for n in states if n not in sigs[k]["inputs"] or n not in sigs[k]["outputs"]]
        if miss:
            print(f"REFUSED: signature {k} lacks state tensors as input + output: {miss[:6]}")
            return 3
    mask = sigs[dk]["inputs"].get("mask")
    kv_len = mask[-1] if mask else None
    for k in pre + dec:
        mk = sigs[k]["inputs"].get("mask")
        if mk and kv_len is not None and mk[-1] != kv_len:
            notes.append(f"signature {k}: mask last dim {mk[-1]} != decode {kv_len}")
    states.sort(key=lambda n: (int(KV.match(n).group(2)), KV.match(n).group(1)))
    L = [f"# ExecutorMetadata generated by executor_skeleton.py from the signatures of {os.path.basename(a.tflite)}",
         f"#   (prefill: {', '.join(pre)}; decode: {dk}). state_buffers only: decode input + output tensors named",
         "#   kv_cache_k_<n> / kv_cache_v_<n>; sequence_axis = the axis whose size equals the decode mask's last",
         f"#   dimension ({kv_len}). max_history_size and attention_mask_settings are not written."]
    blocks = []
    for name in states:
        kind = KV.match(name).group(1)
        shp = sigs[dk]["inputs"][name]
        cand = [i for i, x in enumerate(shp) if kv_len is not None and x == kv_len]
        rule = 2 if kind == "k" else 3
        if len(cand) == 1:
            axis = cand[0]
            if axis != rule:
                notes.append(f"{name}: axis {axis} from the shape {shp} differs from the layout rule {rule}")
        else:
            axis = rule
            notes.append(f"{name}: shape {shp}, mask length {kv_len}: axis by layout rule = {rule}")
        blocks.append((name, kind, axis, shp[axis]))
    L += [f"# note: {n}" for n in notes]
    L.append("llm_executor_metadata {")
    for name, kind, axis, mx in blocks:
        L += ["  state_buffers {", f'    prefill_input_name: "{name}"', f'    prefill_output_name: "{name}"',
              f'    decode_input_name: "{name}"', f'    decode_output_name: "{name}"',
              f"    type: {'TYPE_GLOBAL_KEY_CACHE' if kind == 'k' else 'TYPE_GLOBAL_VALUE_CACHE'}",
              f"    sequence_axis: {axis}", f"    maximum_sequence_length: {mx}", "  }"]
    L.append("}")
    text = "\n".join(L) + "\n"
    from google.protobuf import text_format
    from litert_lm_builder.runtime.proto import executor_metadata_pb2
    msg = executor_metadata_pb2.ExecutorMetadata()
    text_format.Parse(text, msg)
    with open(a.out, "w", encoding="utf-8") as fo:
        fo.write(text)
    summary = dict(out=a.out, state_buffers=len(msg.llm_executor_metadata.state_buffers),
                   serialized_bytes=len(msg.SerializeToString()), prefill=pre, decode=dk, kv_len=kv_len, notes=notes)
    if a.compare:
        shipped = executor_metadata_pb2.ExecutorMetadata()
        text_format.Parse(open(a.compare, encoding="utf-8").read(), shipped)
        x, y = msg.llm_executor_metadata, shipped.llm_executor_metadata
        diffs = []
        if len(x.state_buffers) != len(y.state_buffers):
            diffs.append(f"state_buffers {len(x.state_buffers)} vs shipped {len(y.state_buffers)}")
        sy = {b.decode_input_name: b for b in y.state_buffers}
        for b in x.state_buffers:
            c = sy.get(b.decode_input_name)
            if c is None:
                diffs.append(f"{b.decode_input_name}: not in shipped")
                continue
            for f in ("prefill_input_name", "prefill_output_name", "decode_output_name", "type", "sequence_axis",
                      "maximum_sequence_length"):
                if getattr(b, f) != getattr(c, f):
                    diffs.append(f"{b.decode_input_name}.{f}: {getattr(b, f)} vs shipped {getattr(c, f)}")
        extra = [f for f in ("max_history_size", "attention_mask_settings") if y.HasField(f)]
        summary["compare"] = dict(shipped=a.compare, state_buffer_diffs=diffs, shipped_only_fields=extra)
    print(json.dumps(summary, indent=1))
    return 0


def insert(a):
    text = open(a.toml, encoding="utf-8").read()
    parts = text.split(MARK)
    prefix, blocks = parts[0].rstrip(), [(MARK + p).strip() for p in parts[1:]]
    types = [tomllib.loads(b)["section"][0].get("section_type") for b in blocks]
    if "ExecutorMetadata" in types:
        print(f"REFUSED: {a.toml} already has an ExecutorMetadata section")
        return 3
    pos = types.index("LlmMetadata") + 1 if "LlmMetadata" in types else 0
    rel = os.path.relpath(os.path.abspath(a.pbtext), os.path.dirname(os.path.abspath(a.out)))
    block = "\n".join((MARK, 'section_type = "ExecutorMetadata"', f"data_path = {json.dumps(rel)}"))
    blocks.insert(pos, block)
    with open(a.out, "w", encoding="utf-8") as fo:
        fo.write("\n\n".join(b for b in [prefix] + blocks if b).rstrip() + "\n")
    print(f"inserted ExecutorMetadata at section {pos} of {len(blocks)}")
    return 0


def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    g = sub.add_parser("gen")
    g.add_argument("--tflite", required=True)
    g.add_argument("--out", required=True)
    g.add_argument("--compare", default=None)
    i = sub.add_parser("insert")
    i.add_argument("--toml", required=True)
    i.add_argument("--pbtext", required=True)
    i.add_argument("--out", required=True)
    a = ap.parse_args()
    try:
        return gen(a) if a.cmd == "gen" else insert(a)
    except Exception as e:  # unreadable flatbuffer / TOML / pbtext
        print(f"ERROR: {type(e).__name__}: {e}")
        return 2


if __name__ == "__main__":
    sys.exit(main())
